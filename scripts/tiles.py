def subset(text):
    with tempfile.TemporaryDirectory() as d:
        out = os.path.join(d, 'f.woff2')
        subprocess.run([sys.executable, '-m', 'fontTools.subset', FONT_SRC, '--text=' + text, '--flavor=woff2',
                        '--output-file=' + out, '--layout-features=kern'], check=True)
        return base64.b64encode(open(out, 'rb').read()).decode()


def pixels(art):
    rows = [r for r in art.strip('\n').split('\n')]
    out = []
    for y, row in enumerate(rows):
        for x, ch in enumerate(row):
            if ch in PAL:
                out.append(f'<rect x="{x * C}" y="{y * C}" width="{C}" height="{C}" fill="{PAL[ch]}"/>')
    return ''.join(out), len(rows[0]) * C, len(rows) * C


def extras(kind):
    """The little moving part each object gets, in the art's own coordinates."""
    if kind == 'petals':
        css, els = [], []
        for i, (x, d, dl) in enumerate([(40, 5.5, 0), (90, 6.5, -2), (130, 5, -3.5), (70, 7, -1.2)]):
            css.append(f'@keyframes f{i}{{from{{transform:translate({x}px,40px) rotate(0)}}to{{transform:translate({x - 60}px,170px) rotate(300deg)}}}}'
                       f'.f{i}{{animation:f{i} {d}s linear {dl}s infinite}}')
            els.append(f'<rect class="f{i}" x="-4" y="-4" width="8" height="8" rx="2" fill="{PAL["P"]}"/>')
        return ''.join(css), ''.join(els)
    if kind == 'scan':
        corners = ''.join(f'<path d="{d}" stroke="#2b4fd8" stroke-width="5" fill="none"/>' for d in
                          ['M6 30V6H30', 'M162 6H186V30', 'M6 114V138H30', 'M162 138H186V114'])
        return ('@keyframes blink{0%,100%{opacity:1}50%{opacity:.15}}.scan{animation:blink 1.4s steps(2) infinite}'
                '@keyframes line{from{transform:translateY(10px)}to{transform:translateY(130px)}}.line{animation:line 1.8s ease-in-out infinite alternate}',
                f'<g class="scan">{corners}</g><rect class="line" x="12" y="0" width="168" height="3" fill="#2b4fd8" opacity=".55"/>')
    if kind == 'flag':
        return ('@keyframes wave{0%,100%{transform:rotate(-6deg)}50%{transform:rotate(8deg)}}.flag{animation:wave .9s ease-in-out infinite;transform-origin:150px 110px}',
                '<g class="flag"><rect x="150" y="30" width="5" height="82" fill="#2a2d34"/><path d="M155 32h34l-8 12 8 12h-34z" fill="#ff4d4d"/></g>')
    if kind == 'drop':
        return ('@keyframes drop{0%{transform:translate(78px,-20px) rotate(-20deg);opacity:0}15%{opacity:1}70%{transform:translate(78px,52px) rotate(10deg);opacity:1}85%,100%{transform:translate(78px,70px) rotate(10deg);opacity:0}}'
                '.ph{animation:drop 2.2s ease-in infinite}',
                '<g class="ph"><rect x="0" y="0" width="22" height="36" rx="4" fill="#2a2d34"/><rect x="3" y="4" width="16" height="24" fill="#7b95ff"/></g>')
    if kind == 'notes':
        css, els = [], []
        for i, (x, dl) in enumerate([(70, 0), (105, -1.1), (88, -2.2)]):
            css.append(f'@keyframes n{i}{{0%{{transform:translate({x}px,70px);opacity:0}}20%{{opacity:1}}100%{{transform:translate({x + 18}px,-10px);opacity:0}}}}'
                       f'.n{i}{{animation:n{i} 3.3s ease-out {dl}s infinite}}')
            els.append(f'<g class="n{i}"><rect x="0" y="0" width="6" height="18" fill="#2b4fd8"/><rect x="-8" y="12" width="12" height="9" rx="4" fill="#2b4fd8"/><rect x="0" y="0" width="12" height="5" fill="#2b4fd8"/></g>')
        return ''.join(css), ''.join(els)
    if kind == 'beat':
        return ('@keyframes beat{0%,60%,100%{transform:scale(1)}15%{transform:scale(1.09)}30%{transform:scale(.97)}45%{transform:scale(1.06)}}'
                '.art{animation:beat 1.6s ease-in-out infinite;transform-origin:96px 72px}', '')
    return '', ''


def tile(t, dark):
    bg, ink, soft = ('#0d1117', '#f2f3f5', '#9aa3ad') if dark else ('#f6f5f2', '#141519', '#5c616b')
    body, w, h = pixels(t['art'])
    css, moving = extras(t['anim'])
    font = subset(t['name'] + t['tag'])
    ox, oy = (S - w) // 2, 44
    return f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {S} {S}" width="{S}" height="{S}" role="img" aria-label="{t['name']}: {t['tag']}">
<style>
@font-face{{font-family:IT;src:url(data:font/woff2;base64,{font}) format('woff2');font-weight:100 900}}
.t{{font:700 25px IT,'Helvetica Neue',Arial,sans-serif;letter-spacing:-.6px;fill:{ink};text-anchor:middle}}
.s{{font:500 14.5px IT,'Helvetica Neue',Arial,sans-serif;fill:{soft};text-anchor:middle}}
{css}
@media (prefers-reduced-motion:reduce){{*{{animation:none!important}}}}
</style>
<rect width="{S}" height="{S}" rx="18" fill="{bg}"/>
<g transform="translate({ox},{oy})"><g class="art">{body}</g>{moving}</g>
<text class="t" x="{S // 2}" y="{S - 64}">{t['name']}</text>
<text class="s" x="{S // 2}" y="{S - 38}">{t['tag']}</text>
</svg>'''


for t in TILES:
    for dark in (False, True):
        p = os.path.join(ROOT, 'assets', f'tile-{t["key"]}-{"dark" if dark else "light"}.svg')
        open(p, 'w', encoding='utf8', newline='\n').write(tile(t, dark))
    print(t['key'], os.path.getsize(p) // 1024, 'KB')
